def get_locale():
    lang = request.args.get("lang")
    if lang in LANG:
        session["lang"] = lang
        return lang
    return session.get("lang", "en")


def init_i18n(app):
    @app.before_request
    def _load_language():
        lang = get_locale()
        g.lang = lang
        g.T    = LANG.get(lang, LANG["en"])

    @app.context_processor
    def _inject():
        return {
            "T":            getattr(g, "T",    LANG["en"]),
            "current_lang": getattr(g, "lang", "en"),
        }
